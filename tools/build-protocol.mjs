#!/usr/bin/env node
/**
 * The protocol text in `protocol/**` is the single source of truth.
 *
 * Two consumers need it embedded rather than read from disk:
 *   - the CLI, so `npx bugbridge` works without shipping loose markdown next to dist/
 *   - `web/index.html`, which must stay a single offline file with no fetch() at all
 *
 * This script regenerates both. `--check` fails instead of writing, so CI catches a
 * protocol edit that was never propagated.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const languages = ['en', 'zh-CN'];

const protocol = {};
for (const language of languages) {
  const dir = join(root, 'protocol', language);
  const fragments = {};
  for (const file of readdirSync(dir).sort()) {
    if (!file.endsWith('.md')) continue;
    fragments[file.replace(/\.md$/, '')] = readFileSync(join(dir, file), 'utf8').trimEnd();
  }
  const required = ['00-header', '10-authority', '20-workflow', '30-budget', '40-escalation', '50-redaction',
    'route-global', 'route-china', 'mode-readonly', 'mode-guided', 'mode-auto-safe'];
  const missing = required.filter((name) => !(name in fragments));
  if (missing.length) {
    console.error(`protocol/${language}: missing fragment(s): ${missing.join(', ')}`);
    process.exit(1);
  }
  protocol[language] = fragments;
}

const banner = '// GENERATED by tools/build-protocol.mjs from protocol/**. Do not edit by hand.\n';
const tsSource =
  banner +
  '/* eslint-disable */\n' +
  'export const PROTOCOL_FRAGMENTS: Record<string, Record<string, string>> = ' +
  JSON.stringify(protocol, null, 2) +
  ';\n';

// The schemas live in spec/ so they are consumable by editors and other languages, but
// tsc's rootDir is src/. Inline them rather than reading from disk at runtime, so the
// published dist/ works no matter how it was installed.
const schemaSource =
  banner +
  '/* eslint-disable */\n' +
  ['task', 'project']
    .map(
      (name) =>
        `export const ${name.toUpperCase()}_SCHEMA: Record<string, any> = ` +
        JSON.stringify(JSON.parse(readFileSync(join(root, 'spec', `${name}.schema.json`), 'utf8')), null, 2) +
        ';\n',
    )
    .join('\n');

const jsonPayload = JSON.stringify(protocol);
const targets = [
  { path: join(root, 'src', 'core', 'protocol-data.ts'), next: tsSource },
  { path: join(root, 'src', 'core', 'schema-data.ts'), next: schemaSource },
  { path: join(root, 'web', 'index.html'), next: injectIntoHtml(join(root, 'web', 'index.html'), jsonPayload) },
];

let stale = 0;
for (const target of targets) {
  if (target.next === null) continue;
  let current = null;
  try {
    current = readFileSync(target.path, 'utf8');
  } catch {
    /* first run */
  }
  if (current === target.next) continue;
  stale += 1;
  if (checkOnly) {
    console.error(`out of date: ${target.path.slice(root.length + 1)}`);
  } else {
    writeFileSync(target.path, target.next);
    console.log(`wrote ${target.path.slice(root.length + 1)}`);
  }
}

if (checkOnly && stale > 0) {
  console.error('\nRun `npm run generate` and commit the result.');
  process.exit(1);
}
if (!checkOnly && stale === 0) console.log('protocol artifacts already up to date');

function injectIntoHtml(path, payload) {
  let html;
  try {
    html = readFileSync(path, 'utf8');
  } catch {
    return null; // web/index.html not created yet
  }
  const start = '/* BUGBRIDGE:PROTOCOL:START */';
  const end = '/* BUGBRIDGE:PROTOCOL:END */';
  const from = html.indexOf(start);
  const to = html.indexOf(end);
  if (from === -1 || to === -1) {
    console.error(`web/index.html is missing the ${start} / ${end} markers`);
    process.exit(1);
  }
  // JSON is embedded as a JS literal inside <script>; `</script>` inside a string would
  // terminate the tag early, and U+2028/9 are not valid in JS string literals.
  const safe = payload.replace(/[<\u2028\u2029]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
  return html.slice(0, from + start.length) + '\nconst PROTOCOL = ' + safe + ';\n' + html.slice(to);
}
